#include <stdio.h>


int main(int argc, char *argv[]) {
    printf(argv[1]);  // 취약한 코드 <- 인자를 포맷 스트링으로 직접 전달
    //printf("%s\n", argv[1]); // 안전한 코드 <- 인자를 데이터로 하나만 전달 
}

/*
    1. "%x %x %x %x" 형태로 실행
    -> b02500 b04c30 1f970011 b02500 
    2. "%p %p %p %p" 형태로 실행 
    -> 0000000000BA2500 0000000000BA4C30 0000000055D10011 0000000000BA2500
       "%d %d %d %d" 형태로 실행 
    -> 7808256 7818288 1734213649 7808256
       "%s %s %s %s" 형태로 실행 
    -> 다음 인자에 있는 주소를 따라가서 문자열을 읽는데, 유효하지 않은 주소를 읽는 순간 
       접근 위반으로 종료되고, 그 전까지 버퍼에 있던 출력도 함께 사라져 아무것도 출력되지 않음 
    
    안전한 코드로 실행 
    3. "%x %x %x %x" 형태로 실행 
    -> "%x %x %x %x"
       "%p %p %p %p" 형태로 실행 
    -> "%p %p %p %p"
       "%d %d %d %d" 형태로 실행 
    -> "%d %d %d %d"
       "%s %s %s %s" 형태로 실행 
    -> "%s %s %s %s" 

    4. 취약한 코드 vs 안전한 코드 
     취약한 코드는 인자가 포맷 문자열이 돼서 인자가 전달되는 자리에서 값을 순서대로 꺼내 읽는다.
     꺼낸 값을 숫자로 출력하는 세 형식(%x, %p, %d)의 1~4번째에서 모두 같은 위치를 읽고 있으며, 
     값의 하위 비트는 일치하지만 실행마다 주소 배치가 달라 상위 비트가 바뀐다. 
     안전한 코드는 포맷 문자열이 코드에 고정된 %s 하나로, 사용자가 "%x %x"를 넣어도 
     포맷으로 해석되지 않고 출력할 문자열로 해석된다. 
     이로 인해 취약한 코드는 입력한 형식 수만큼 값이 나왔지만, 안전한 코드는 입력한 문자열이 그대로 1개 나온다.  
*/